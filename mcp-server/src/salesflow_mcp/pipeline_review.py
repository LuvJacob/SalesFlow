"""Scheduled pipeline risk review: build, render and store a digest.

Reuses ``risk_engine.analyze_opportunity_risk`` unchanged. This module reads the
CRM JSON files fresh on every call, so each run sees the latest data.

Definitions (also stated in every digest):
- Active opportunity: any opportunity whose stage does not start with "Closed".
- Flagged deal: risk rating is Medium Risk or High Risk (score >= 2).
- Ranking: risk score (desc), then deal value (desc), then opportunity_id.

CRM text is untrusted data. It is rendered as plain text, never executed or
interpreted as instructions. Stdout is never written to (MCP stdio safety).
"""

from __future__ import annotations

import json
import logging
import os
import re
from datetime import datetime
from pathlib import Path
from typing import Any
from zoneinfo import ZoneInfo

from .risk_engine import analyze_opportunity_risk
from .schedule_spec import DEFAULT_TIMEZONE, to_iso
from .schedule_store import is_valid_id

log = logging.getLogger("salesflow.scheduler")

DIGEST_VERSION = 1
FLAGGED_RATINGS = ("High Risk", "Medium Risk")
LIMITATION_NOTE = (
    "This digest is generated by a local scheduler that only runs while its host machine and the "
    "scheduler process are running. It is stored on disk for Bob to retrieve; it is not pushed into "
    "Bob and no message has been sent."
)
DISCLAIMER = (
    "Risk scores come from transparent heuristic rules for prioritisation. They are not statistically "
    "validated or machine-learning predictions. Missing CRM fields are reported as Unknown and are not "
    "treated as negative evidence."
)
_CTRL = re.compile(r"[\x00-\x1f\x7f]")


class PipelineDataError(Exception):
    """CRM data could not be read. ``code`` is stable; ``message`` is user-safe."""

    def __init__(self, code: str, message: str):
        super().__init__(message)
        self.code = code
        self.message = message


# --------------------------------------------------------------------------- data


def data_dir() -> Path:
    override = os.environ.get("SALESFLOW_DATA_DIR")
    if override:
        return Path(override)
    return Path(__file__).resolve().parents[3] / "data"


def _load(path: Path, key: str, required: tuple[str, ...]) -> tuple[list[dict], int, dict]:
    try:
        with path.open("r", encoding="utf-8") as fh:
            doc = json.load(fh)
    except (OSError, ValueError) as exc:
        log.error("CRM data load failed: %s (%s)", path.name, type(exc).__name__)
        raise PipelineDataError(
            "crm_unavailable", "CRM data is unavailable or unreadable, so no review could be produced."
        ) from exc
    records = doc.get(key) if isinstance(doc, dict) else None
    if not isinstance(records, list):
        log.error("CRM data shape invalid: %s", path.name)
        raise PipelineDataError("crm_invalid", "CRM data is malformed, so no review could be produced.")
    valid = [r for r in records if isinstance(r, dict) and all(k in r for k in required)]
    meta = doc.get("_meta") if isinstance(doc.get("_meta"), dict) else {}
    return valid, len(records) - len(valid), meta


def _clean(value: Any, limit: int = 300) -> str:
    text = _CTRL.sub(" ", str(value if value is not None else ""))
    return " ".join(text.split())[:limit]


# --------------------------------------------------------------------------- build


def build_digest(
    *,
    now: datetime,
    trigger: str,
    run_id: str,
    schedule: dict[str, Any] | None = None,
    seller: str | None = None,
    tz_name: str = DEFAULT_TIMEZONE,
) -> dict[str, Any]:
    """Evaluate active opportunities and return a structured digest. Raises PipelineDataError."""
    base = data_dir()
    opps, skipped_opps, opp_meta = _load(base / "opportunities.json", "opportunities", ("opportunity_id", "account_id"))
    accounts, skipped_accts, _ = _load(base / "accounts.json", "accounts", ("account_id", "name"))
    acct_map = {a["account_id"]: a for a in accounts}

    local_now = now.astimezone(ZoneInfo(tz_name))
    today = local_now.date().isoformat()
    scope = seller.strip().casefold() if seller and seller.strip() else None

    analysed: list[tuple[dict, dict]] = []
    excluded_closed = out_of_scope = 0
    for o in opps:
        if str(o.get("stage", "")).strip().casefold().startswith("closed"):
            excluded_closed += 1
            continue
        if scope is not None and str(o.get("seller", "")).strip().casefold() != scope:
            out_of_scope += 1
            continue
        analysed.append((o, analyze_opportunity_risk(o, acct_map.get(o["account_id"]), current_date_str=today)))

    analysed.sort(key=lambda p: (-p[1]["risk_score"], -(p[0].get("value") or 0.0), str(p[0]["opportunity_id"])))

    distribution = {"High Risk": [0, 0.0], "Medium Risk": [0, 0.0], "Low Risk": [0, 0.0]}
    factor_counts: dict[str, int] = {}
    unknown_counts: dict[str, int] = {}
    flagged: list[dict[str, Any]] = []
    total_value = 0.0
    for o, a in analysed:
        value = float(o.get("value") or 0.0)
        total_value += value
        bucket = distribution.setdefault(a["risk_rating"], [0, 0.0])
        bucket[0] += 1
        bucket[1] += value
        for u in a["unknown_factors"]:
            unknown_counts[u] = unknown_counts.get(u, 0) + 1
        if a["risk_rating"] not in FLAGGED_RATINGS:
            continue
        for r in a["flagged_risks"]:
            factor_counts[r["factor"]] = factor_counts.get(r["factor"], 0) + 1
        acct = acct_map.get(o["account_id"]) or {}
        ordered = sorted(a["flagged_risks"], key=lambda r: -r["score_contribution"])
        actions: list[str] = []
        for r in ordered:
            if r["recommended_action"] not in actions:
                actions.append(r["recommended_action"])
        if a["unknown_factors"]:
            actions.append(
                "Confirm missing CRM fields (not scored as risk): " + ", ".join(a["unknown_factors"]) + "."
            )
        flagged.append({
            "rank": len(flagged) + 1,
            "opportunity_id": _clean(o["opportunity_id"], 80),
            "account_id": _clean(o["account_id"], 80),
            "account_name": _clean(acct.get("name", "Unknown account"), 120),
            "opportunity_name": _clean(a["name"], 160),
            "stage": _clean(a["stage"], 60),
            "seller": _clean(a["seller"], 60),
            "value": value,
            "close_date": _clean(o.get("close_date"), 20) or "Unknown",
            "risk_score": a["risk_score"],
            "risk_rating": a["risk_rating"],
            "evidence": [
                {"factor": r["factor"], "evidence": r["evidence"], "score_contribution": r["score_contribution"]}
                for r in ordered
            ],
            "recommended_actions": actions,
            "unknown_factors": list(a["unknown_factors"]),
            "source_id": _clean(o.get("source_id"), 80) or None,
        })

    flagged_value = sum(d["value"] for d in flagged)
    notes: list[str] = []
    if not analysed:
        notes.append(
            "No active opportunities matched"
            + (" the seller scope." if scope is not None else ".")
            + " Nothing was evaluated."
        )
    if skipped_opps or skipped_accts:
        notes.append(f"Skipped malformed CRM records: {skipped_opps} opportunity, {skipped_accts} account.")

    return {
        "digest_version": DIGEST_VERSION,
        "run_id": run_id,
        "schedule_id": schedule["schedule_id"] if schedule else None,
        "schedule_name": schedule["name"] if schedule else None,
        "trigger": trigger,
        "generated_at": to_iso(now),
        "generated_at_local": local_now.isoformat(timespec="seconds"),
        "timezone": tz_name,
        "review_date": today,
        "seller_scope": seller.strip() if seller and seller.strip() else "All sellers",
        "synthetic_data": bool(opp_meta.get("synthetic", False)),
        "definitions": {
            "active_opportunity": "Stage does not start with 'Closed'.",
            "flagged_deal": "Risk rating is Medium Risk or High Risk (score >= 2).",
            "ranking": "Risk score descending, then deal value descending, then opportunity_id.",
        },
        "summary": {
            "active_deals_analyzed": len(analysed),
            "total_active_value": total_value,
            "flagged_deals": len(flagged),
            "flagged_value": flagged_value,
            "risk_distribution": {
                k: {"count": v[0], "value": v[1]} for k, v in distribution.items()
            },
            "top_risk_factors": [
                {"factor": f, "count": c}
                for f, c in sorted(factor_counts.items(), key=lambda kv: (-kv[1], kv[0]))
            ],
            "unknown_factor_counts": dict(sorted(unknown_counts.items())),
            "excluded_closed": excluded_closed,
            "excluded_other_sellers": out_of_scope,
        },
        "flagged_deals": flagged,
        "not_flagged_opportunity_ids": [
            _clean(o["opportunity_id"], 80) for o, a in analysed if a["risk_rating"] not in FLAGGED_RATINGS
        ],
        "notes": notes,
        "disclaimer": DISCLAIMER,
        "limitations": LIMITATION_NOTE,
    }


# --------------------------------------------------------------------------- render


def _money(value: float) -> str:
    return f"${value:,.0f}"


def render_markdown(d: dict[str, Any]) -> str:
    s = d["summary"]
    lines = [
        f"# Pipeline risk briefing: {d['schedule_name'] or 'On-demand review'}",
        "",
        f"- Generated: {d['generated_at_local']} ({d['timezone']}); UTC {d['generated_at']}",
        f"- Trigger: {d['trigger']}  |  Run: `{d['run_id']}`",
        f"- Seller scope: {d['seller_scope']}",
        f"- Data: {'SYNTHETIC demo CRM data' if d['synthetic_data'] else 'CRM data (not marked synthetic)'}",
        "",
        "## Summary",
        "",
        f"- Active deals analysed: {s['active_deals_analyzed']} ({_money(s['total_active_value'])})",
        f"- Flagged deals (Medium/High risk): {s['flagged_deals']} ({_money(s['flagged_value'])})",
    ]
    for rating in ("High Risk", "Medium Risk", "Low Risk"):
        b = s["risk_distribution"].get(rating, {"count": 0, "value": 0.0})
        lines.append(f"- {rating}: {b['count']} deal(s), {_money(b['value'])}")
    if s["top_risk_factors"]:
        lines += ["", "Top risk factors:"]
        lines += [f"- {f['factor']}: {f['count']} deal(s)" for f in s["top_risk_factors"]]
    for note in d["notes"]:
        lines += ["", f"> Note: {note}"]

    lines += ["", "## Flagged deals, highest risk first", ""]
    if not d["flagged_deals"]:
        lines.append("No deals were flagged.")
    for deal in d["flagged_deals"]:
        lines += [
            f"### {deal['rank']}. {deal['account_name']}: {deal['opportunity_name']}",
            "",
            f"- Rating: **{deal['risk_rating']}** (score {deal['risk_score']})",
            f"- Opportunity: `{deal['opportunity_id']}`  |  Stage: {deal['stage']}  |  Seller: {deal['seller']}",
            f"- Value: {_money(deal['value'])}  |  Close date: {deal['close_date']}",
            "",
            "Supporting evidence:",
        ]
        lines += [
            f"- {e['factor']} (+{e['score_contribution']}): {e['evidence']}" for e in deal["evidence"]
        ]
        lines += ["", "Recommended seller actions:"]
        lines += [f"{i}. {a}" for i, a in enumerate(deal["recommended_actions"], 1)]
        if deal["unknown_factors"]:
            lines += ["", "Unknown (not scored): " + ", ".join(deal["unknown_factors"])]
        lines.append("")

    if d["not_flagged_opportunity_ids"]:
        lines += ["## Not flagged (Low Risk)", ""]
        lines += [f"- `{oid}`" for oid in d["not_flagged_opportunity_ids"]]
        lines.append("")
    lines += ["## Scope and limits", "", d["disclaimer"], "", d["limitations"], ""]
    return "\n".join(lines)


# --------------------------------------------------------------------------- store


def _atomic_write(path: Path, text: str) -> None:
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


def write_digest_files(digest_dir: Path, run_id: str, digest: dict[str, Any]) -> tuple[str, str]:
    """Write digest.json and digest.md under digest_dir/<run_id>/. Returns relative paths."""
    if not is_valid_id(run_id, "run"):
        raise ValueError("invalid run id")
    target = digest_dir / run_id
    target.mkdir(parents=True, exist_ok=True)
    _atomic_write(target / "digest.json", json.dumps(digest, indent=2, sort_keys=False) + "\n")
    _atomic_write(target / "digest.md", render_markdown(digest))
    return f"{run_id}/digest.json", f"{run_id}/digest.md"
